import { open, org, shot, close } from './h.mjs';
const { page } = await open('owner', 'd');
await page.goto(org('/bang-gia/di-chuyen'));
await page.waitForTimeout(1200);
const m = page.locator('main');
await m.getByRole('radio', { name: 'Theo km' }).click();
await m.getByLabel('Mức cố định mỗi lần đi').fill('200000');
await m.getByLabel('Đơn giá mỗi km').fill('10000');
await m.getByLabel('Bán kính miễn phí').fill('3');
await m.getByLabel('Phí tối thiểu').fill('50000');
const sw = m.getByRole('switch', { name: 'Tính cả chiều về' });
if ((await sw.getAttribute('aria-checked')) !== 'true') await sw.click();
await m.getByRole('button', { name: 'Thêm bậc' }).click();
await m.getByRole('button', { name: 'Thêm bậc' }).click();
await page.waitForTimeout(200);
console.log(await m.evaluate((d) => [...d.querySelectorAll('input')].map((e) => `${e.getAttribute('aria-label') ?? ''}|${e.labels?.[0]?.innerText ?? ''}|${e.value}`).join('\n')));
const f = (l, v) => m.getByLabel(l, { exact: true }).fill(v);
await f('Bậc 1: từ km', '3'); await f('Bậc 1: đến km', '10'); await f('Bậc 1: phí', '100000');
await f('Bậc 2: từ km', '10'); await f('Bậc 2: đến km', ''); await f('Bậc 2: phí', '250000');
await m.getByRole('button', { name: 'Lưu' }).click();
await page.waitForTimeout(1200);
console.log('SAU LƯU:', (await m.innerText()).slice(0, 600));
// studio
await m.getByRole('button', { name: 'Thêm studio / cửa hàng' }).click();
await page.waitForTimeout(400);
const dlg = page.getByRole('dialog');
console.log(await dlg.evaluate((d) => [...d.querySelectorAll('input,textarea,select,button')].map((e) => `${e.tagName}|${e.getAttribute('aria-label') ?? ''}|${e.labels?.[0]?.innerText ?? ''}|${e.innerText ?? ''}`).join('\n')));
await shot(page, 'kham-studio-moi');
await close();
