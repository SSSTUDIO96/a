import { open, org, shot, close, seed } from './h.mjs';
import { api } from './api.mjs';
const pk = (await api('GET', '/packages?pageSize=50')).body.items;
const pd = pk.find((p) => p.code === 'G-PD');
const linh = seed.users.linh.membershipId;
const body = (s, e, name) => ({ newCustomer: { fullName: name, phone: '0911000111' }, eventDate: '2026-11-22T00:00:00+07:00', lines: [{ kind: 'PACKAGE', packageId: pd.id, quantity: 1, locationType: 'STUDIO', scheduledStart: `2026-11-22T${s}:00+07:00`, scheduledEnd: `2026-11-22T${e}:00+07:00`, staff: [{ membershipId: linh, role: 'PRIMARY' }] }] });
const A = await api('POST', '/contracts', body('10:00', '11:00', 'Khách đua A'));
console.log('A', A.status, A.body.code);
const { page } = await open('owner', 'd');
await page.goto(org('/hop-dong/' + A.body.id));
await page.waitForTimeout(2500);
const xn = page.getByRole('button', { name: 'Xác nhận hợp đồng' });
console.log('A trước đua: xác nhận khoá?', await xn.isDisabled());
const B = await api('POST', '/contracts', body('10:30', '11:30', 'Khách đua B'));
const Bc = await api('POST', `/contracts/${B.body.id}/status`, { to: 'CONFIRMED' });
console.log('B', B.body.code, 'xác nhận →', Bc.status);
await xn.click();
await page.waitForTimeout(3000);
await shot(page, 'hd-409-khi-xac-nhan-1440');
const txt = await page.locator('main').innerText();
console.log('SAU 409:', txt.match(/[^\n]*(Trùng|trùng|đã có lịch|LH-)[^\n]*/g), '| trạng thái:', txt.match(/Lập hợp đồng HD-\S+|Hợp đồng HD-\S+|Đã xác nhận[^\n]*|Nháp/g)?.slice(0, 3));
console.log('A trên máy chủ:', (await api('GET', '/contracts/' + A.body.id)).body.status);
await close();
