import { open, org, shot, close } from './h.mjs';
import { api } from './api.mjs';
const { page } = await open('owner', 'd');
const list = await api('GET', '/contracts?pageSize=20');
const id = list.body.items.find((c) => c.code === 'HD-000001').id;
await page.goto(org('/hop-dong/' + id));
await page.waitForTimeout(2000);
await shot(page, 'hd1-mo-lai-1440');
console.log((await page.locator('main').innerText()).slice(0, 900));
const calls = [];
page.on('request', (r) => { if (r.method() !== 'GET' && r.url().includes('/contracts')) calls.push(r.method() + ' ' + r.url().split('/orgs/')[1]); });
const btn = page.getByRole('button', { name: 'Xác nhận hợp đồng' });
await btn.dblclick();
await btn.click({ force: true, timeout: 1000 }).catch(() => {});
await page.waitForTimeout(2500);
console.log('CÁC LỆNH GHI:', calls);
await shot(page, 'hd1-da-xac-nhan-1440');
console.log((await page.locator('main').innerText()).slice(0, 2500));
await close();
