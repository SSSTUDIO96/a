import { open, org, shot, close } from './h.mjs';
const { page } = await open('owner', 'd');
await page.goto(org('/lich?ngay=2026-11-21'));
await page.waitForTimeout(2000);
await page.getByRole('button', { name: /09:00/ }).first().click();
await page.waitForTimeout(800);
let dlg = page.getByRole('dialog');
await dlg.getByRole('button', { name: 'Sửa' }).click();
await page.waitForTimeout(600);
await dlg.getByRole('textbox', { name: 'Giờ kết thúc' }).fill('10:00');
await dlg.getByLabel('Tên ca').click();
await dlg.getByRole('button', { name: 'Lưu' }).click();
await page.waitForTimeout(1500);
console.log('sau Lưu, hộp:', (await dlg.innerText().catch(() => 'ĐÃ ĐÓNG')).replace(/\n/g, ' | ').slice(0, 300));
await shot(page, 'lich-sau-luu-sua');
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
console.log('Esc → hộp còn?', await dlg.isVisible().catch(() => false));
// Huỷ ca 10:30
await page.getByRole('button', { name: /10:30/ }).first().click();
await page.waitForTimeout(800);
dlg = page.getByRole('dialog');
await dlg.getByRole('button', { name: 'Huỷ lịch' }).click();
await page.waitForTimeout(500);
const d2 = page.getByRole('dialog').last();
console.log('HỘP HUỶ LỊCH:', (await d2.innerText()).replace(/\n/g, ' | '));
await d2.getByRole('textbox').fill('Khách báo hoãn');
await d2.getByRole('button', { name: /Huỷ lịch|Xác nhận/ }).last().click();
await page.waitForTimeout(1500);
console.log('sau huỷ:', (await page.getByRole('dialog').first().innerText().catch(() => 'đóng')).replace(/\n/g, ' | ').slice(0, 200));
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
await shot(page, 'lich-sau-sua-huy-1440');
await close();
